"""Write a `ConvertResult` as the §3.5 tree — the only code that writes results.

The tree is built in `<out>.partial/`, `run.json` last, then swapped into place
(§3.12 rule 1): an earlier run's extra `chart-NNN` files can never sit beside a
new `run.json`, and a crash mid-write leaves no `run.json` to trust.

Nothing is replaced or deleted unless gdi wrote it (PR 11): a folder that shares
a PDF's name, or its `.partial`/`.old` sibling's, and holds anything else is
refused with `ForeignFolderError`, never renamed aside.

`document.json` references the image files in the tree rather than embedding
them as base64 (§3.12 rule 2); chart pictures point at the crop Granite Vision
saw, other pictures at Docling's crop, and page images exist only on request.
"""

from __future__ import annotations

import copy
import json
import os
import re
import shutil
from dataclasses import asdict
from pathlib import Path
from typing import TYPE_CHECKING, Any

from granite_document_intelligence.config import CHART_CROP_SCALE

if TYPE_CHECKING:
    from docling_core.types.doc import DoclingDocument
    from PIL.Image import Image

    from granite_document_intelligence.api import Chunk, ConvertResult, KvpResult

PARTIAL_SUFFIX = ".partial"
OLD_SUFFIX = ".old"
RUN_JSON = "run.json"
KVP_JSON = "kvp.json"
CHUNKS_JSONL = "chunks.jsonl"
# Every name the §3.5 tree can hold, by folder; `is_ours` matches against them.
_TOP_FILES = frozenset(
    {"document.md", "document.json", KVP_JSON, CHUNKS_JSONL, RUN_JSON}
)
_SUBDIR_FILES = {
    "charts": re.compile(r"chart-\d{3,}\.(png|csv|raw\.txt|summary\.txt|py)"),
    "tables": re.compile(r"table-\d{3,}\.(csv|html)"),
    "pictures": re.compile(r"picture-\d{3,}\.png"),
    "pages": re.compile(r"page-\d{3,}\.png"),
}


class ForeignFolderError(OSError):
    """A folder gdi would replace or delete holds something gdi did not write."""


def chart_code_header(source: str, page_no: int) -> str:
    """The comment every `chart-NNN.py` opens with (§3.10): it is model output."""
    return (
        f"# Generated by granite-vision-4.1-4b from {source} page {page_no}. "
        "Untrusted: review before running.\n"
    )


def _save_png(image: Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, format="PNG")


def _referenced_document(
    result: ConvertResult,
    image_paths: dict[str, tuple[Image, str]],
    page_paths: dict[int, str],
) -> DoclingDocument:
    """A copy of the document whose image refs are relative paths in the tree."""
    from docling_core.types.doc import ImageRef

    doc = copy.deepcopy(result.document)
    chart_refs = {chart.ref for chart in result.charts}
    for picture in doc.pictures:
        entry = image_paths.get(picture.self_ref)
        if entry is None:
            picture.image = None
            continue
        image, rel = entry
        if picture.self_ref in chart_refs:
            dpi = round(72 * CHART_CROP_SCALE)
        else:
            dpi = picture.image.dpi if picture.image else 72
        ref = ImageRef.from_pil(image, dpi=dpi)
        ref.uri = Path(rel)
        picture.image = ref
    for page_no, page in doc.pages.items():
        rel = page_paths.get(page_no)
        if rel is None or page.image is None:
            page.image = None
            continue
        page.image.uri = Path(rel)
    return doc


def _tree_bytes(root: Path) -> int:
    return sum(p.stat().st_size for p in root.rglob("*") if p.is_file())


def _write_tree(result: ConvertResult, staging: Path) -> None:
    from docling_core.types.doc import ImageRefMode

    source = result.source.name
    image_paths: dict[str, tuple[Image, str]] = {}
    for chart in result.charts:
        stem = f"charts/chart-{chart.index:03d}"
        _save_png(chart.image, staging / f"{stem}.png")
        image_paths[chart.ref] = (chart.image, f"{stem}.png")
        if chart.csv is not None:
            (staging / f"{stem}.csv").write_text(chart.csv, encoding="utf-8")
        elif chart.raw_csv:
            # Nothing parseable: keep what the model wrote rather than lose it (§17).
            (staging / f"{stem}.raw.txt").write_text(chart.raw_csv, encoding="utf-8")
        if chart.summary is not None:
            (staging / f"{stem}.summary.txt").write_text(
                chart.summary + "\n", encoding="utf-8"
            )
        if chart.code is not None:
            code = chart_code_header(source, chart.page_no) + chart.code + "\n"
            (staging / f"{stem}.py").write_text(code, encoding="utf-8")

    for picture in result.pictures:
        if picture.image is None:
            continue
        rel = f"pictures/picture-{picture.index:03d}.png"
        _save_png(picture.image, staging / rel)
        image_paths[picture.ref] = (picture.image, rel)

    for table in result.tables:
        stem = staging / "tables" / f"table-{table.index:03d}"
        stem.parent.mkdir(parents=True, exist_ok=True)
        table.dataframe.to_csv(stem.with_suffix(".csv"), index=False)
        stem.with_suffix(".html").write_text(table.html, encoding="utf-8")

    page_paths: dict[int, str] = {}
    if result.run.options.get("save_page_images"):
        for page_no, page in result.document.pages.items():
            image = page.image.pil_image if page.image else None
            if image is not None:
                rel = f"pages/page-{page_no:03d}.png"
                _save_png(image, staging / rel)
                page_paths[page_no] = rel

    if result.kvp is not None:
        (staging / KVP_JSON).write_text(
            json.dumps(kvp_record(result.kvp), indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
    if result.run.options.get("chunks", True):
        with (staging / CHUNKS_JSONL).open("w", encoding="utf-8") as f:
            for chunk in result.chunks:
                f.write(json.dumps(chunk_record(chunk), ensure_ascii=False) + "\n")

    doc = _referenced_document(result, image_paths, page_paths)
    doc.save_as_json(staging / "document.json", image_mode=ImageRefMode.PLACEHOLDER)
    markdown = doc.export_to_markdown(image_mode=ImageRefMode.REFERENCED)
    (staging / "document.md").write_text(markdown + "\n", encoding="utf-8")


def kvp_record(kvp: KvpResult) -> dict[str, Any]:
    """`kvp.json` (§3.5): pages keyed by page number, as JSON object keys are strings."""
    return {
        "pages": {str(page): answer for page, answer in kvp.pages.items()},
        "merged": kvp.merged,
        "conflicts": kvp.conflicts,
        "valid": kvp.valid,
        "errors": kvp.errors,
        "raw": {str(page): text for page, text in kvp.raw.items()},
    }


def chunk_record(chunk: Chunk) -> dict[str, Any]:
    """One `chunks.jsonl` line, with §3.9's keys."""
    return {
        "id": chunk.id,
        "text": chunk.text,
        "contextualized": chunk.contextualized,
        "headings": chunk.headings,
        "page_nos": chunk.page_nos,
        "doc_item_refs": chunk.refs,
    }


def run_record(result: ConvertResult, output_bytes: int) -> dict[str, Any]:
    """`run.json`'s content: provenance and costs, never document text (§3.13 rule 5)."""
    run = result.run
    return {
        "status": "ok",
        "source": result.source.name,
        "input_sha256": run.input_sha256,
        "page_count": run.page_count,
        "options": run.options,
        "models": run.models,
        "versions": run.versions,
        "timings_ms": run.timings_ms,
        "pages": [asdict(page) for page in run.pages],
        "chart_ms": run.chart_ms,
        "kvp_ms": run.kvp_ms,
        "peak_memory_bytes": run.peak_memory_bytes,
        "warnings": run.warnings,
        "counts": {
            "charts": len(result.charts),
            "pictures": len(result.pictures),
            "tables": len(result.tables),
            "chunks": len(result.chunks),
            "kvp_pages": len(result.kvp.pages) if result.kvp is not None else 0,
        },
        "output_bytes": output_bytes,
    }


def is_ours(folder: Path) -> bool:
    """Whether gdi may replace or delete `folder` (PR 11).

    It may when `folder` is a real directory holding nothing but names from the
    §3.5 layout, which covers an empty folder, crash residue with no `run.json`
    yet, and a tree whose `run.json` was lost. v1.0.0 renamed aside and deleted
    whatever sat at the output path, so `gdi convert Documents.pdf -o ~` would
    have deleted `~/Documents`. Anything else, a user's file, a symlink, a
    folder that cannot be read, is "not ours".
    """
    if folder.is_symlink() or not folder.is_dir():
        return False
    try:
        return all(_is_layout_entry(entry) for entry in folder.iterdir())
    except OSError:
        return False


def _is_layout_entry(entry: Path) -> bool:
    pattern = _SUBDIR_FILES.get(entry.name)
    if pattern is None:
        return entry.name in _TOP_FILES and _is_file(entry)
    if entry.is_symlink() or not entry.is_dir():
        return False
    return all(
        _is_file(child) and pattern.fullmatch(child.name) for child in entry.iterdir()
    )


def _is_file(path: Path) -> bool:
    return path.is_file() and not path.is_symlink()


def siblings(out_dir: Path) -> tuple[Path, Path]:
    """`out_dir`'s staging and swap folders: `<out>.partial` and `<out>.old`."""
    return (
        out_dir.with_name(out_dir.name + PARTIAL_SUFFIX),
        out_dir.with_name(out_dir.name + OLD_SUFFIX),
    )


def check_replaceable(out_dir: Path) -> None:
    """Refuse, before anything is written, a folder the swap would destroy (PR 11)."""
    for folder in (out_dir, *siblings(out_dir)):
        if (folder.exists() or folder.is_symlink()) and not is_ours(folder):
            raise ForeignFolderError(
                f"{folder} exists and was not written by gdi; move it or convert "
                "into another output directory"
            )


def swap_into_place(staging: Path, out_dir: Path) -> None:
    """Replace `out_dir` with `staging`: two renames within one directory (§3.12 rule 1)."""
    _, old = siblings(out_dir)
    if old.exists():
        shutil.rmtree(old)
    if out_dir.exists():
        os.rename(out_dir, old)
    os.rename(staging, out_dir)
    if old.exists():
        shutil.rmtree(old)


def _staging(out_dir: Path) -> Path:
    check_replaceable(out_dir)
    out_dir.parent.mkdir(parents=True, exist_ok=True)
    staging, _ = siblings(out_dir)
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir()
    return staging


def _write_run_json(staging: Path, record: dict[str, Any]) -> None:
    (staging / RUN_JSON).write_text(
        json.dumps(record, indent=2) + "\n", encoding="utf-8"
    )


def save(result: ConvertResult, out_dir: Path) -> None:
    out_dir = Path(out_dir)
    staging = _staging(out_dir)
    _write_tree(result, staging)
    record = run_record(result, _tree_bytes(staging))
    # Written last: only a complete tree carries a run.json (§3.5).
    _write_run_json(staging, record)
    swap_into_place(staging, out_dir)


def save_error(
    out_dir: Path,
    source: Path,
    error: dict[str, Any],
    input_sha256: str | None,
    options: dict[str, Any],
) -> None:
    """Replace `out_dir` with a tree holding only an error `run.json` (§3.8).

    It goes through the same swap as a success, so a failed re-run replaces a
    stale success rather than sitting beside its files (§3.12 rule 1), and
    resume, which trusts only `"status": "ok"`, runs the PDF again next time.
    `error` is `safety.error_record`'s: no locals, no foreign frames.
    """
    out_dir = Path(out_dir)
    staging = _staging(out_dir)
    record = {
        "status": "error",
        "source": source.name,
        "input_sha256": input_sha256,
        "options": options,
        "error": error,
    }
    _write_run_json(staging, record)
    swap_into_place(staging, out_dir)
