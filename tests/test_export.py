"""`save()` and the §3.5 tree, from a DoclingDocument built in code (no models)."""

import json
from pathlib import Path
from typing import Any

import pytest
from conftest import build_document

from granite_document_intelligence.api import (
    Chart,
    Chunk,
    ConvertOptions,
    ConvertResult,
    KvpResult,
    Picture,
    RunInfo,
    Table,
)


def _chart(doc: Any, index: int, **overrides: Any) -> Chart:
    from PIL import Image

    fields: dict[str, Any] = {
        "index": index,
        "page_no": 1,
        "kind": "bar_chart",
        "confidence": 0.97,
        "image": Image.new("RGB", (360, 270), "blue"),
        "csv": "Region,Revenue\nNorth,120\n",
        "raw_csv": "```csv\nRegion,Revenue\nNorth,120\n```",
        "summary": "Revenue is highest in the North.",
        "code": None,
        "ref": doc.pictures[index - 1].self_ref,
    }
    fields.update(overrides)
    return Chart(**fields)


def make_result(
    *,
    charts: int = 1,
    options: ConvertOptions | None = None,
    kvp: KvpResult | None = None,
    chunks: list[Chunk] | None = None,
    **chart_overrides: Any,
) -> ConvertResult:
    doc = build_document(charts=charts)
    options = options or ConvertOptions()
    chart_list = [_chart(doc, i, **chart_overrides) for i in range(1, charts + 1)]
    logo = doc.pictures[charts]
    table = doc.tables[0]
    return ConvertResult(
        source=Path("report.pdf"),
        document=doc,
        charts=chart_list,
        pictures=[
            Picture(
                index=1,
                page_no=1,
                kind="logo",
                image=logo.image.pil_image if logo.image else None,
                ref=logo.self_ref,
            )
        ],
        tables=[
            Table(
                index=1,
                page_no=1,
                dataframe=table.export_to_dataframe(doc=doc),
                html=table.export_to_html(doc=doc),
                ref=table.self_ref,
            )
        ],
        kvp=kvp,
        chunks=chunks or [],
        run=RunInfo(
            input_sha256="0" * 64,
            page_count=1,
            options=options.as_dict(),
            models={"manifest": {}},
            versions={"docling": "test"},
            timings_ms={"total": 1.0},
            pages=[],
            chart_ms=[1.0] * charts,
            peak_memory_bytes={"phase_a": 1},
            warnings=[],
        ),
    )


def _tree(root: Path) -> set[str]:
    return {str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()}


class TestTree:
    def test_writes_exactly_the_documented_files(self, tmp_path: Path) -> None:
        out = tmp_path / "out" / "report"
        make_result().save(out)
        assert _tree(out) == {
            "document.md",
            "document.json",
            "run.json",
            "chunks.jsonl",
            "charts/chart-001.png",
            "charts/chart-001.csv",
            "charts/chart-001.summary.txt",
            "pictures/picture-001.png",
            "tables/table-001.csv",
            "tables/table-001.html",
        }
        assert not (tmp_path / "out" / "report.partial").exists()

    def test_chart_and_table_contents(self, tmp_path: Path) -> None:
        out = tmp_path / "report"
        make_result().save(out)
        assert (
            out / "charts/chart-001.csv"
        ).read_text() == "Region,Revenue\nNorth,120\n"
        assert (
            (out / "charts/chart-001.summary.txt").read_text().startswith("Revenue is")
        )
        assert (out / "tables/table-001.csv").read_text().splitlines() == [
            "Region,Revenue",
            "North,120",
        ]
        assert "<table>" in (out / "tables/table-001.html").read_text()

    def test_a_chart_without_a_table_writes_no_csv_but_keeps_the_raw_text(
        self, tmp_path: Path
    ) -> None:
        out = tmp_path / "report"
        make_result(csv=None, raw_csv="no table here").save(out)
        assert not (out / "charts/chart-001.csv").exists()
        assert (out / "charts/chart-001.raw.txt").read_text() == "no table here"

    def test_chart_code_carries_the_untrusted_header(self, tmp_path: Path) -> None:
        out = tmp_path / "report"
        make_result(code="import matplotlib").save(out)
        first = (out / "charts/chart-001.py").read_text().splitlines()[0]
        assert first == (
            "# Generated by granite-vision-4.1-4b from report.pdf page 1. "
            "Untrusted: review before running."
        )

    def test_page_images_only_on_request(self, tmp_path: Path) -> None:
        make_result().save(tmp_path / "default")
        assert not (tmp_path / "default" / "pages").exists()
        make_result(options=ConvertOptions(save_page_images=True)).save(
            tmp_path / "pages"
        )
        assert (tmp_path / "pages" / "pages" / "page-001.png").is_file()


class TestDocumentJson:
    def test_holds_no_base64_and_every_image_ref_resolves(self, tmp_path: Path) -> None:
        out = tmp_path / "report"
        make_result(options=ConvertOptions(save_page_images=True)).save(out)
        text = (out / "document.json").read_text()
        assert "base64" not in text
        data = json.loads(text)
        uris = [p["image"]["uri"] for p in data["pictures"] if p.get("image")]
        uris += [p["image"]["uri"] for p in data["pages"].values() if p.get("image")]
        assert sorted(uris) == [
            "charts/chart-001.png",
            "pages/page-001.png",
            "pictures/picture-001.png",
        ]
        for uri in uris:
            assert (out / uri).is_file()

    def test_a_chart_points_at_the_crop_granite_vision_saw(
        self, tmp_path: Path
    ) -> None:
        out = tmp_path / "report"
        make_result().save(out)
        chart = json.loads((out / "document.json").read_text())["pictures"][0]
        assert chart["image"]["size"] == {"width": 360.0, "height": 270.0}
        assert chart["image"]["dpi"] == 108

    def test_no_page_image_is_kept_unless_requested(self, tmp_path: Path) -> None:
        out = tmp_path / "report"
        make_result().save(out)
        pages = json.loads((out / "document.json").read_text())["pages"]
        assert all(page.get("image") is None for page in pages.values())

    def test_the_markdown_links_the_chart_by_its_path(self, tmp_path: Path) -> None:
        out = tmp_path / "report"
        make_result().save(out)
        markdown = (out / "document.md").read_text()
        assert "charts/chart-001.png" in markdown
        assert "base64" not in markdown

    def test_saving_does_not_change_the_result(self, tmp_path: Path) -> None:
        result = make_result()
        before = result.document.export_to_dict()
        result.save(tmp_path / "report")
        assert result.document.export_to_dict() == before


class TestRunJson:
    def test_records_status_provenance_and_size(self, tmp_path: Path) -> None:
        out = tmp_path / "report"
        make_result().save(out)
        record = json.loads((out / "run.json").read_text())
        assert record["status"] == "ok"
        assert record["input_sha256"] == "0" * 64
        assert record["options"] == ConvertOptions().as_dict()
        assert record["counts"] == {
            "charts": 1,
            "pictures": 1,
            "tables": 1,
            "chunks": 0,
            "kvp_pages": 0,
        }
        others = sum(
            p.stat().st_size
            for p in out.rglob("*")
            if p.is_file() and p.name != "run.json"
        )
        assert record["output_bytes"] == others

    def test_is_written_last(self, tmp_path: Path) -> None:
        out = tmp_path / "report"
        make_result().save(out)
        newest = max(
            (p for p in out.rglob("*") if p.is_file()),
            key=lambda p: p.stat().st_mtime_ns,
        )
        assert newest.name == "run.json"


class TestAtomicSwap:
    def test_a_rerun_with_fewer_charts_leaves_no_stale_file(
        self, tmp_path: Path
    ) -> None:
        # §3.12 rule 1: chart-004/005 must not survive beside a new run.json.
        out = tmp_path / "report"
        make_result(charts=3).save(out)
        assert (out / "charts/chart-003.csv").is_file()
        make_result(charts=1).save(out)
        assert sorted(p.name for p in (out / "charts").iterdir()) == [
            "chart-001.csv",
            "chart-001.png",
            "chart-001.summary.txt",
        ]
        assert not (tmp_path / "report.old").exists()

    def test_a_crash_mid_write_leaves_the_previous_tree_intact(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        from granite_document_intelligence import export

        out = tmp_path / "report"
        make_result().save(out)
        before = _tree(out)

        def crash(*_: Any) -> None:
            raise OSError("disk full")

        monkeypatch.setattr(export, "run_record", crash)
        with pytest.raises(OSError, match="disk full"):
            make_result(charts=2).save(out)
        assert _tree(out) == before
        # The residue is a .partial with no run.json, which nothing trusts.
        assert not (tmp_path / "report.partial" / "run.json").exists()

    def test_a_leftover_partial_is_replaced(self, tmp_path: Path) -> None:
        (tmp_path / "report.partial").mkdir()
        (tmp_path / "report.partial" / "chart-009.csv").write_text("stale")
        make_result().save(tmp_path / "report")
        assert not (tmp_path / "report" / "chart-009.csv").exists()


KVP = KvpResult(
    pages={1: {"name": "Alex Q. Sample"}, 2: None},
    merged={"name": "Alex Q. Sample"},
    conflicts=[],
    valid=True,
    errors=[],
    raw={1: '{"name": "Alex Q. Sample"}', 2: "no idea"},
)
CHUNK = Chunk(
    id="chunk-0001",
    text="Revenue rose in every region.",
    contextualized="Quarterly report\nRevenue rose in every region.",
    headings=["Quarterly report"],
    page_nos=[1],
    refs=["#/texts/1"],
)


class TestKvpJson:
    def test_only_with_a_schema(self, tmp_path: Path) -> None:
        make_result().save(tmp_path / "report")
        assert not (tmp_path / "report" / "kvp.json").exists()

    def test_records_every_field_with_pages_as_keys(self, tmp_path: Path) -> None:
        make_result(kvp=KVP).save(tmp_path / "report")
        record = json.loads((tmp_path / "report" / "kvp.json").read_text())
        assert record == {
            "pages": {"1": {"name": "Alex Q. Sample"}, "2": None},
            "merged": {"name": "Alex Q. Sample"},
            "conflicts": [],
            "valid": True,
            "errors": [],
            "raw": {"1": '{"name": "Alex Q. Sample"}', "2": "no idea"},
        }

    def test_document_text_stays_out_of_run_json(self, tmp_path: Path) -> None:
        # run.json is provenance and costs, never document text (§3.13 rule 5).
        make_result(kvp=KVP, chunks=[CHUNK]).save(tmp_path / "report")
        run = (tmp_path / "report" / "run.json").read_text()
        assert "Alex" not in run and "Revenue rose" not in run
        assert json.loads(run)["counts"]["kvp_pages"] == 2


class TestChunksJsonl:
    def test_one_line_per_chunk_with_the_documented_keys(self, tmp_path: Path) -> None:
        make_result(chunks=[CHUNK, CHUNK]).save(tmp_path / "report")
        lines = (tmp_path / "report" / "chunks.jsonl").read_text().splitlines()
        assert len(lines) == 2
        record = json.loads(lines[0])
        assert list(record) == [
            "id",
            "text",
            "contextualized",
            "headings",
            "page_nos",
            "doc_item_refs",
        ]
        assert record["doc_item_refs"] == ["#/texts/1"]

    def test_absent_with_chunks_off(self, tmp_path: Path) -> None:
        make_result(options=ConvertOptions(chunks=False)).save(tmp_path / "report")
        assert not (tmp_path / "report" / "chunks.jsonl").exists()
